// Namespace Imports (* as):

// Namespace imports allow you to import all named exports from a module into a single object.
// Instead of importing each function or variable separately, you can access everything through one namespace.

//Ex:

export const a = 10;
export const b = 20;

export function add(x, y) {
  return x + y;
}

export function subtract(x, y) {
  return x - y;
}
